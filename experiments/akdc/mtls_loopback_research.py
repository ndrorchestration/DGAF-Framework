"""AKDC Gate 17: real ephemeral-CA mutual TLS over 127.0.0.1, research only.

The local CA and leaf certificates are generated by the test runner, never
committed. Validating a fixture client's CA chain DOES NOT authorize an
operation, establish an externally authenticated principal, or secure key
custody. The receiver writes only a synthetic local SQLite marker.
"""

from __future__ import annotations

import argparse
import http.client
import json
import ssl
from contextlib import closing
from http.server import ThreadingHTTPServer
from pathlib import Path
from typing import Any

from experiments.akdc.idempotent_consumer_research import (
    ConsumerRefusal,
    SQLiteIdempotentConsumerResearch,
)
from experiments.akdc.loopback_consumer_research import (
    FIXTURE_KEYS,
    PATH,
    FixtureHTTPHandler,
    canonical_body,
    mac,
)
from experiments.akdc.mrtr_outbox_research import SQLiteOutboxResearch


def client_context(ca: str, certificate: str | None, key: str | None) -> ssl.SSLContext:
    ctx = ssl.create_default_context(ssl.Purpose.SERVER_AUTH, cafile=ca)
    ctx.minimum_version = ssl.TLSVersion.TLSv1_3
    ctx.check_hostname = True
    if (certificate is None) != (key is None):
        raise ValueError("client cert/key must be supplied together")
    if certificate is not None and key is not None:
        ctx.load_cert_chain(certfile=certificate, keyfile=key)
    return ctx


def run_mtls_server(receiver_db: str, ca: str, cert: str, key: str) -> None:
    receiver = SQLiteIdempotentConsumerResearch(receiver_db)
    server_ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    server_ctx.minimum_version = ssl.TLSVersion.TLSv1_3
    server_ctx.load_cert_chain(certfile=cert, keyfile=key)
    server_ctx.load_verify_locations(cafile=ca)
    server_ctx.verify_mode = ssl.CERT_REQUIRED
    with ThreadingHTTPServer(("127.0.0.1", 0), FixtureHTTPHandler) as server:
        server.receiver = receiver  # type: ignore[attr-defined]
        server.socket = server_ctx.wrap_socket(server.socket, server_side=True)
        print(json.dumps({"port": server.server_port, "tls": "TLSv1.3", "client_cert": "REQUIRED"}), flush=True)
        server.serve_forever(poll_interval=0.05)


def post_mtls(
    port: int,
    key: str,
    payload: str,
    *,
    ca: str,
    cert: str | None,
    private_key: str | None,
    epoch: str = "fixture-epoch-a",
    drop_reply: bool = False,
    invalid_mac: bool = False,
    hostname: str = "127.0.0.1",
) -> tuple[int, dict[str, Any]]:
    body = canonical_body(key, payload, drop_reply=drop_reply)
    secret = FIXTURE_KEYS[epoch]
    digest = mac(body, secret)
    if invalid_mac:
        digest = "0" * 64 if digest != "0" * 64 else "1" * 64
    ctx = client_context(ca, cert, private_key)
    conn = http.client.HTTPSConnection(hostname, port, context=ctx, timeout=6)
    try:
        conn.request(
            "POST",
            PATH,
            body=body,
            headers={
                "Content-Type": "application/json",
                "X-AKDC-Fixture-Epoch": epoch,
                "X-AKDC-Fixture-MAC": digest,
            },
        )
        response = conn.getresponse()
        return response.status, json.loads(response.read())
    finally:
        conn.close()


def deliver_mtls(
    sender: SQLiteOutboxResearch,
    port: int,
    *,
    ca: str,
    cert: str,
    private_key: str,
    epoch: str = "fixture-epoch-a",
    drop_reply: bool = False,
) -> str:
    """Sender ACK follows separate receiver-local COMMIT; no two-DB atomicity."""
    with closing(sender._connect()) as conn:
        try:
            conn.execute("BEGIN IMMEDIATE")
            sender._check_schema(conn)
            row = conn.execute(
                "SELECT tag, payload FROM outbox WHERE status='PENDING' ORDER BY rowid LIMIT 1"
            ).fetchone()
            if row is None:
                conn.execute("COMMIT")
                return "NO_PENDING"
            tag, payload = row
            try:
                status, response = post_mtls(
                    port, tag, payload, ca=ca, cert=cert, private_key=private_key, epoch=epoch, drop_reply=drop_reply
                )
            except (OSError, ssl.SSLError, http.client.HTTPException):
                conn.execute("ROLLBACK")
                return "ACK_UNKNOWN_PENDING"
            if status != 200 or response.get("authority") != "NOT_GRANTED":
                raise ConsumerRefusal("TLS fixture response refused")
            outcome = response.get("status")
            if outcome not in ("FIRST_RECEIVER_MARKER", "DUPLICATE_RECEIVER_MARKER"):
                raise ConsumerRefusal("unrecognized receiver result")
            conn.execute("INSERT INTO local_effect VALUES (?, 'SYNTHETIC_DB_MARKER')", (tag,))
            conn.execute("UPDATE outbox SET status='APPLIED' WHERE tag=?", (tag,))
            conn.execute("UPDATE receipt SET status='APPLIED' WHERE tag=?", (tag,))
            conn.execute("COMMIT")
            return str(outcome)
        except BaseException:
            if conn.in_transaction:
                conn.execute("ROLLBACK")
            raise


def main() -> None:
    parser = argparse.ArgumentParser(description="synthetic 127.0.0.1 mutual TLS receiver")
    parser.add_argument("--receiver-db", required=True)
    parser.add_argument("--ca", required=True)
    parser.add_argument("--cert", required=True)
    parser.add_argument("--key", required=True)
    args = parser.parse_args()
    for name in (args.ca, args.cert, args.key):
        if not Path(name).is_file():
            raise ValueError("TLS fixture requires existing certificate files")
    run_mtls_server(args.receiver_db, args.ca, args.cert, args.key)


if __name__ == "__main__":
    main()
